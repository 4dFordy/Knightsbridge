import { logoSvg, MIN_SIZE, type LogoGround, type LogoVariant } from "@/brand/logo/logo";

type Props = {
  variant?: LogoVariant;
  ground?: LogoGround;
  /** Display width in CSS pixels. */
  width: number;
  className?: string;
};

/**
 * Renders an Innit logo from the logo specification.
 * Below 160 px wide the horizontal and stacked lockups switch to the ticket alone (spec A9).
 * The nav lockup is designed for 120–160 px and is exempt.
 */
export function Logo({ variant = "nav", ground = "navy", width, className }: Props) {
  const tooSmall = (variant === "horizontal" || variant === "stacked") && width < MIN_SIZE.horizontalWidthPx;
  const shown: LogoVariant = tooSmall ? "ticket" : variant;
  return (
    <span
      data-logo={shown}
      className={`inline-block align-middle leading-none [&>svg]:block [&>svg]:h-auto [&>svg]:w-full ${className ?? ""}`}
      style={{ width }}
      // The SVG is generated by our own code from fixed brand values, never from user input.
      dangerouslySetInnerHTML={{ __html: logoSvg(shown, ground) }}
    />
  );
}
