// Builds src/brand/logo/wordmark.generated.ts from the Montserrat Black font file.
// Run: npm run brand:wordmark  (only needed if the font or the spec changes).
//
// Spec (brand book A3, A10): "innit", lower case, Montserrat Black (900), letter-spacing -0.02em.
// The i's are dotless (ı) with separate round dots so the dots can be coloured.
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import opentype from "opentype.js";

const require = createRequire(import.meta.url);
const fontFile = require.resolve("@fontsource/montserrat/files/montserrat-latin-900-normal.woff");
const font = opentype.loadSync(fontFile);
const UPM = font.unitsPerEm; // 1000
const LETTER_SPACING = -0.02 * UPM;
const TEXT = "ınnıt"; // ınnıt

const glyphs = [...TEXT].map((ch) => font.charToGlyph(ch));
let x = 0;
const parts = [];
const dots = [];
const dotless = glyphs[0];
const dotlessBox = dotless.getBoundingBox();
const stemWidth = dotlessBox.x2 - dotlessBox.x1;
// The dot sits where Montserrat Black's own i-dot sits: same top, diameter = stem width.
const dotTop = font.charToGlyph("i").getBoundingBox().y2;

glyphs.forEach((g, i) => {
  // Paths in SVG space: baseline at y = 0, y grows downwards.
  const d = g.getPath(x, 0, UPM).toPathData(2);
  parts.push(d);
  if (g === dotless || g.name === dotless.name) {
    dots.push({ cx: x + (dotlessBox.x1 + dotlessBox.x2) / 2, cy: -(dotTop - stemWidth / 2), r: stemWidth / 2 });
  }
  const next = glyphs[i + 1];
  x += g.advanceWidth + (next ? font.getKerningValue(g, next) + LETTER_SPACING : 0);
});

// Bounding box of the letters as placed above.
let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
x = 0;
glyphs.forEach((g, i) => {
  const b = g.getBoundingBox();
  minX = Math.min(minX, x + b.x1);
  maxX = Math.max(maxX, x + b.x2);
  minY = Math.min(minY, -b.y2);
  maxY = Math.max(maxY, -b.y1);
  const next = glyphs[i + 1];
  x += g.advanceWidth + (next ? font.getKerningValue(g, next) + LETTER_SPACING : 0);
});

const out = `// GENERATED by scripts/build-wordmark.mjs from Montserrat Black. Do not edit by hand.
// Units: font units (1000 = the wordmark's font size). Baseline at y = 0, y grows downwards.

export const WORDMARK = {
  unitsPerEm: ${UPM},
  /** Letters "ınnıt" (dotless i's), one path. */
  path: ${JSON.stringify(parts.join(""))},
  /** The two round i-dots, coloured separately. */
  dots: ${JSON.stringify(dots.map((d) => ({ cx: +d.cx.toFixed(2), cy: +d.cy.toFixed(2), r: +d.r.toFixed(2) })))},
  /** Bounding box of the letters (without dots). */
  letters: { minX: ${minX.toFixed(2)}, maxX: ${maxX.toFixed(2)}, minY: ${minY.toFixed(2)}, maxY: ${maxY.toFixed(2)} },
  /** Font metrics used for the lockups. */
  capHeight: ${font.tables.os2.sCapHeight},
  xHeight: ${font.tables.os2.sxHeight},
  stemWidth: ${stemWidth},
} as const;
`;

writeFileSync(new URL("../src/brand/logo/wordmark.generated.ts", import.meta.url), out);
console.log("Wrote src/brand/logo/wordmark.generated.ts", { dots, minX, maxX, minY, maxY });
